import '../../src/server/load-env';
import assert from 'node:assert/strict';
import { privateKeyToAccount } from 'viem/accounts';
import { createSiweMessage } from 'viem/siwe';
import { database, one } from '../../src/server/database';
import { chainId } from '../../src/lib/config';
assert.equal(chainId,31337,'This check is local only.');
const base='http://localhost:3020';
const account=privateKeyToAccount('0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80');
const nonce=await(await fetch(base+'/api/auth/nonce')).json();
const message=createSiweMessage({address:account.address,chainId:31337,domain:nonce.domain,uri:nonce.uri,version:'1',nonce:nonce.nonce,issuedAt:new Date(),expirationTime:new Date(Date.now()+300_000)});
const headers={'content-type':'application/json',origin:base,'x-flat-league':'1'};
const session=await fetch(base+'/api/auth/verify',{method:'POST',headers,body:JSON.stringify({message,signature:await account.signMessage({message})})});
assert.equal(session.status,200);
const cookie=session.headers.get('set-cookie')!.split(';')[0];
const db=await database();
const saved=await one(db,'SELECT input_json FROM fl_drafts ORDER BY created_at DESC LIMIT 1');
const input=JSON.parse(String(saved!.input_json));
await db.close();
input.startAt=Date.now()+120_000;input.endAt=input.startAt+180_000;
const response=await fetch(base+'/api/competition-drafts',{method:'POST',headers:{...headers,cookie},body:JSON.stringify(input)});
const result=await response.json();
console.log('Draft API:',response.status,result);
assert.equal(response.status,201);
